  function hardwareMeta() {
    const cpu = getCpu();
    const gpu = getGpu();
    const fr = state.language === "fr";
    const match = String(cpu.coresLabel || "").match(/(\d+)C\s*\/\s*(\d+)T/i);
    const cpuInfo = match
      ? (fr ? `${match[1]} cœurs / ${match[2]} threads` : `${match[1]} cores / ${match[2]} threads`)
      : cpu.coresLabel;
    const boost = fr ? `jusqu'à ${cpu.boost}` : `up to ${cpu.boost}`;
    byId("cpu-meta").textContent = `${cpuInfo} · ${boost}`;

    let feature = fr ? "Frame Generation non disponible" : "Frame Generation unavailable";
    if (gpu.frameGen) {
      if (gpu.brand === "nvidia" && gpu.gen >= 50) feature = fr ? "Multi Frame Generation pris en charge" : "Multi Frame Generation supported";
      else feature = fr ? "Frame Generation pris en charge" : "Frame Generation supported";
    }
    byId("gpu-meta").textContent = `${gpu.vram} GB VRAM · ${feature}`;
  }

  function friendlyFrameGenNote() {
    const note = byId("frame-generation-capability");
    if (!note) return;
    const gpu = getGpu();
    const game = getGame();
    const fr = state.language === "fr";

    if (!gpu?.frameGen || !game?.frameGen) {
      note.textContent = fr ? "Non disponible avec cette carte graphique ou ce jeu." : "Not available with this graphics card or game.";
      return;
    }
    if (gpu.brand === "nvidia" && gpu.gen >= 50) {
      note.textContent = fr
        ? "RTX 50 · Choisissez MFG 2X, 3X ou 4X. Le gain réel dépend du jeu et des FPS de base."
        : "RTX 50 · Choose MFG 2X, 3X or 4X. The real gain depends on the game and base FPS.";
      return;
    }
    if (gpu.brand === "nvidia" && gpu.gen >= 40) {
      note.textContent = fr
        ? "RTX 40 · Frame Generation classique uniquement. Le Multi Frame Generation n'est pas disponible."
        : "RTX 40 · Standard Frame Generation only. Multi Frame Generation is not available.";
      return;
    }
    note.textContent = fr ? "Frame Generation disponible lorsque le jeu le prend en charge." : "Frame Generation is available when the game supports it.";
  }

